def on_recommend(user, genre):
    if state["retraining"]:
        return {feedback_msg: BUSY}
    if user is None:
        return {feedback_msg: " Please log in again."}
    recs = engine.recommend(user, genre_filter=None if genre == "Any" else genre)
    if recs.empty:
        return {rec_table: None, movie_pick: gr.update(choices=[], value=None),
                feedback_msg: "No movies found for this genre."}
    table = pd.DataFrame({
        "Rank": recs["rank"],
        "Title": recs["title"],
        "Genres": recs["genres"].str.replace("|", ", ", regex=False),
        "Score": recs["display"],
        "Source": recs["source"],
    })
    choices = [(f"{r['rank']}. {r['title']}", str(r["movieId"])) for _, r in recs.iterrows()]
    return {rec_table: table,
            movie_pick: gr.update(choices=choices, value=None),
            feedback_msg: "Watched one of these? Rate it below — it is saved for the next retraining."}


