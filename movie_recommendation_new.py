def _logged_in_menu(engine, user):
    while True:
        # 4B Load profile + 6B Load history
        profile = engine.load_profile(user)
        mode = "NCF (personal embedding)" if profile["has_ncf_embedding"] \
            else "Cold-start (no embedding until next retraining)"
        print(f"\n--- User ID {engine.display_user_id(user)} | "
              f"ratings: {len(profile['history'])} | "
              f"genres: {', '.join(profile['preferred_genres']) or '—'} | mode: {mode}")
        print("1. Get recommendations")
        print("2. View my ratings in this app (latest 15)")
        print("3. Logout")
        choice = _ask("Select: ")

        if choice == "1":
            # 5B Choose recommendation genre
            raw = _ask("Genre for recommendations (Enter = any): ")
            genre = None
            if raw:
                genre = engine.catalog.normalise_genre(raw)
                if genre is None:
                    print("✗ Unknown genre.")
                    continue
            recs = engine.recommend(user, genre_filter=genre)       # steps 7–10
            _print_recommendations(recs)
            if recs.empty:
                continue

            # 11 User rates movies -> 12 Save
            print("Rate any of these? Format: rank=rating, e.g. 1=4.5, 3=2  (Enter to skip)")
            raw = _ask("> ")
            if not raw:
                continue
            feedback = {}
            for part in raw.split(","):
                if "=" not in part:
                    continue
                rank_s, rating_s = part.split("=", 1)
                try:
                    rank = int(rank_s.strip())
                except ValueError:
                    continue
                hit = recs[recs["rank"] == rank]
                if not hit.empty:
                    feedback[int(hit.iloc[0]["movieId"])] = rating_s.strip()
            ok, error = engine.submit_feedback(user, feedback)
            print("✓ Feedback saved." if ok else f"✗ {error}")

        elif choice == "2":
            app_ratings = engine.db.get_ratings(user["id"])
            if not app_ratings:
                print("No ratings in the app yet.")
            for mid, r in list(app_ratings.items())[-15:]:
                print(f"  {r:.1f}  {engine.catalog.title(mid)}")

        elif choice == "3":
            print("Logged out.")
            return
        else:
            print("✗ Invalid choice.")


