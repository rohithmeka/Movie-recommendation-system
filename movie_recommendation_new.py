# STEP 13 (part 2) — OFFLINE MODEL RETRAINING
# Same data cleaning, chronological split, ID encoding, NCF model and
# training settings as the offline phase. The app ratings are added to
# the TRAINING data only, so the test set stays the same and the new
# test RMSE/MAE can be compared with the old ones.
# ============================================================

def _batches(users, movies, ratings, batch_size, shuffle):
    """Slices tensors that are already on the GPU (faster than a DataLoader)."""
    if shuffle:
        order = torch.randperm(len(ratings), device=ratings.device)
    else:
        order = torch.arange(len(ratings), device=ratings.device)
    for start in range(0, len(ratings), batch_size):
        idx = order[start:start + batch_size]
        yield users[idx], movies[idx], ratings[idx]


def _rmse_mae(model, data, batch_size, use_amp):
    model.eval()
    squared, absolute = 0.0, 0.0
    with torch.no_grad():
        for users, movies, ratings in _batches(*data, batch_size, shuffle=False):
            if use_amp:
                with torch.autocast(device_type="cuda", dtype=torch.float16):
                    predictions = model(users, movies)
            else:
                predictions = model(users, movies)
            predictions = predictions.float().clamp(0.5, 5.0)
            squared += torch.sum((predictions - ratings) ** 2).item()
            absolute += torch.sum(torch.abs(predictions - ratings)).item()
    n = len(data[2])
    return float(np.sqrt(squared / n)), absolute / n


def retrain_model(engine):
    config = engine.config
    device = engine.device
    use_amp = device.type == "cuda"
    batch_size = config["batch_size_gpu"] if use_amp else config["batch_size_cpu"]
    np.random.seed(config["seed"])
    torch.manual_seed(config["seed"])

    print("\n" + "=" * 70)
    print("STEP 13 — OFFLINE MODEL RETRAINING")
    print("=" * 70)

    # 1. ratings collected by the app
    app_ratings = engine.export_feedback_for_retraining(config["feedback_path"])
    if app_ratings.empty:
        print("No ratings in the app yet — nothing new to learn from.")
        return
    print(f"{len(app_ratings)} app ratings from {app_ratings['userId'].nunique()} users "
          f"saved to {config['feedback_path']}")

    # free the app's copy of ratings.csv while training; it is rebuilt at the end
    engine.catalog = None
    gc.collect()
    try:
        _train_and_save(engine, app_ratings, device, use_amp, batch_size)
    finally:
        print("Reloading the movie catalog ...")
        engine.catalog = MovieCatalog(
            config["movies_path"], config["ratings_path"], config["prior_votes"]
        )
        engine.reload_model()
    print("✓ App now uses the retrained model.")


def _train_and_save(engine, app_ratings, device, use_amp, batch_size):
    config = engine.config

    # 2. same cleaning + chronological 80/10/10 split as the offline phase.
    #    Memory: Colab has ~12 GB RAM, so the data is read with small types (float32 =
    #    4 bytes, it can also hold missing values) and the app's own copy of ratings.csv
    #    is freed during training (it is loaded again afterwards).
    print("Loading ratings.csv ...")
    ratings = pd.read_csv(
        config["ratings_path"],
        dtype={"userId": "float32", "movieId": "float32", "rating": "float32",
               "timestamp": "float64"},
    )
    # one rating per user-movie pair (this also removes exact duplicate rows)
    ratings = ratings.drop_duplicates(subset=["userId", "movieId"])
    # a rating without a timestamp cannot be placed in time -> drop it before the split
    ratings = ratings.dropna(subset=["userId", "movieId", "rating", "timestamp"])
    ratings = ratings.astype({"userId": "int32", "movieId": "int32", "timestamp": "int64"})
    ratings = ratings.sort_values(["userId", "timestamp"]).reset_index(drop=True)
    gc.collect()
    count = ratings.groupby("userId")["movieId"].transform("count").to_numpy()
    position = ratings.groupby("userId").cumcount().to_numpy()
    train_df = ratings[position < count * 0.8]
    val_df = ratings[(position >= count * 0.8) & (position < count * 0.9)]
    test_df = ratings[position >= count * 0.9]

    # 3. add the app ratings to the training data (skip any pair already in ratings.csv)
    app_ratings = app_ratings.astype(
        {"userId": "int32", "movieId": "int32", "rating": "float32", "timestamp": "int64"}
    )
    check = app_ratings.merge(ratings[["userId", "movieId"]], on=["userId", "movieId"],
                              how="left", indicator=True)
    app_ratings = app_ratings[(check["_merge"] == "left_only").to_numpy()]
    train_df = pd.concat([train_df, app_ratings], ignore_index=True)
    print(f"Train: {len(train_df):,} (incl. {len(app_ratings)} app ratings) | "
          f"Validation: {len(val_df):,} | Test: {len(test_df):,}")
    del ratings, count, position
    gc.collect()

    # 4. ID encoding from training data only (same as the offline phase)
    user_to_index = {int(u): i for i, u in enumerate(train_df["userId"].unique())}
    movie_to_index = {int(m): i for i, m in enumerate(train_df["movieId"].unique())}

    def to_tensors(df):
        users = df["userId"].map(user_to_index)
        movies = df["movieId"].map(movie_to_index)
        known = users.notna() & movies.notna()          # drop movies unseen in training
        return (
            torch.tensor(users[known].to_numpy(dtype=np.int64), device=device),
            torch.tensor(movies[known].to_numpy(dtype=np.int64), device=device),
            torch.tensor(df["rating"][known].to_numpy(dtype=np.float32), device=device),
        )

    train_data, val_data, test_data = to_tensors(train_df), to_tensors(val_df), to_tensors(test_df)
    del train_df, val_df, test_df
    gc.collect()
    print(f"Users in model: {len(user_to_index):,} | Movies in model: {len(movie_to_index):,}")

    # 5. train a fresh NCF (same architecture + settings)
    model = NCF(len(user_to_index), len(movie_to_index), config["embedding_dim"]).to(device)
    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=config["learning_rate"],
                                 weight_decay=config["weight_decay"])
    scaler = torch.amp.GradScaler("cuda") if use_amp else None

    best_val_rmse, best_state, bad_epochs = float("inf"), None, 0
    for epoch in range(1, config["retrain_epochs"] + 1):
        model.train()
        total_loss = torch.zeros((), device=device)
        for users, movies, targets in _batches(*train_data, batch_size, shuffle=True):
            optimizer.zero_grad(set_to_none=True)
            if use_amp:
                with torch.autocast(device_type="cuda", dtype=torch.float16):
                    loss = criterion(model(users, movies), targets)
                scaler.scale(loss).backward()
                scaler.step(optimizer)
                scaler.update()
            else:
                loss = criterion(model(users, movies), targets)
                loss.backward()
                optimizer.step()
            total_loss += loss.detach().float() * len(targets)
        train_loss = total_loss.item() / len(train_data[2])

        val_rmse, val_mae = _rmse_mae(model, val_data, batch_size, use_amp)
        print(f"Epoch {epoch}/{config['retrain_epochs']} | train MSE {train_loss:.4f} | "
              f"val RMSE {val_rmse:.4f} | val MAE {val_mae:.4f}")
        if val_rmse < best_val_rmse:
            best_val_rmse, best_state, bad_epochs = val_rmse, copy.deepcopy(model.state_dict()), 0
        else:
            bad_epochs += 1
            if bad_epochs >= config["patience"]:
                print("Early stopping triggered.")
                break

    model.load_state_dict(best_state)
    test_rmse, test_mae = _rmse_mae(model, test_data, batch_size, use_amp)
    print(f"Test RMSE: {test_rmse:.4f}   Test MAE: {test_mae:.4f}")

    # 6. save (same format as the offline phase) and reload in the app
    checkpoint = {
        "model_state_dict": model.state_dict(),
        "num_users": len(user_to_index),
        "num_movies": len(movie_to_index),
        "embedding_dim": config["embedding_dim"],
        "user_to_index": user_to_index,
        "movie_to_index": movie_to_index,
        "index_to_user": {i: u for u, i in user_to_index.items()},
        "index_to_movie": {i: m for m, i in movie_to_index.items()},
        "test_rmse": test_rmse,
        "test_mae": test_mae,
        "app_ratings_used": len(app_ratings),
    }
    os.makedirs(os.path.dirname(config["model_path"]) or ".", exist_ok=True)
    torch.save(checkpoint, config["model_path"])
    print("Retrained model saved to", config["model_path"])

    del model, train_data, val_data, test_data, best_state
    gc.collect()
    if use_amp:
        torch.cuda.empty_cache()


