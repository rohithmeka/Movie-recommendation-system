def _ask(prompt):
    return input(prompt).strip()


def _print_recommendations(recs):
    if recs.empty:
        print("\nNo recommendations found for that choice.")
        return
    print("\n" + "=" * 78)
    print(f"{'#':<3} {'Title':<45} {'Score':<17} Source")
    print("-" * 78)
    for _, r in recs.iterrows():
        title = r["title"] if len(r["title"]) <= 44 else r["title"][:41] + "..."
        print(f"{r['rank']:<3} {title:<45} {r['display']:<17} {r['source']}")
        print(f"    {r['genres']}  (movieId {r['movieId']})")
    print("=" * 78)


def _choose_genres(engine):
    print("\nAvailable genres:")
    print(", ".join(engine.catalog.genres))
    while True:
        raw = _ask("Choose 2–3 favourite genres (comma separated): ")
        genres, error = engine.validate_genres([g for g in raw.split(",") if g.strip()])
        if error:
            print("✗", error)
        else:
            return genres


def _initial_ratings(engine, genres):
    pool = engine.onboarding_movies(genres)
    print("\nRate popular movies (0.5–5.0). Press Enter to skip one you haven't seen.")
    print("You need at least 5 ratings; you can stop after 5 by typing 'done'.")
    ratings = {}
    for _, m in pool.iterrows():
        if len(ratings) >= 10:
            break
        raw = _ask(f"  {m['title']}  [{m['genres']}]  -> ")
        if raw.lower() == "done":
            if len(ratings) >= 5:
                break
            print(f"  Need {5 - len(ratings)} more rating(s).")
            raw = _ask(f"  {m['title']}  [{m['genres']}]  -> ")
        if raw == "":
            continue
        r = engine.parse_rating(raw)
        if r is None:
            print("  ✗ Invalid rating, skipped (use 0.5, 1.0, ... 5.0).")
            continue
        ratings[int(m["movieId"])] = r
    return ratings


def _new_user_flow(engine, username):
    # 3A Register
    error = engine.validate_username(username)
    if error:
        print("✗", error)
        return None
    print(f"\nNo account called '{username}' was found → you are a NEW USER.")
    while True:
        password = _ask("Create a password (min 6 chars): ")
        user_id, error = engine.register(username, password)
        if error:
            print("✗", error)
        else:
            break
    user = engine.db.get_user(user_id)
    print(f"✓ Account created. Your User ID is {engine.display_user_id(user)} "
          f"(you can log in later with this ID or your username).")
    _onboard(engine, user)
    return engine.db.get_user(user_id)


def _onboard(engine, user):
    # 4A + 5A + 6A
    genres = _choose_genres(engine)
    while True:
        ratings = _initial_ratings(engine, genres)
