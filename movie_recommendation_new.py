class RecommenderEngine:

    CSV_ACCOUNT_PREFIX = "movielens_"

    def __init__(self, config):
        self.config = config
        self._check_weights()

        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        print("Device:", self.device)

        self.catalog = MovieCatalog(
            config["movies_path"], config["ratings_path"], config["prior_votes"]
        )
        self.db = UserDatabase(config["db_path"])

        # User IDs that exist in ratings.csv = "existing users" of the dataset.
        # App-registered users get IDs ABOVE the largest dataset ID, so the
        # two kinds of ID can never clash.
        self.csv_user_ids = set(np.unique(self.catalog.rating_user_ids).tolist())
        self.max_csv_user_id = max(self.csv_user_ids)
        print(f"Existing users in ratings.csv: {len(self.csv_user_ids):,} "
              f"(IDs up to {self.max_csv_user_id})")

        # Step 7 — load trained NCF model + mappings
        self.reload_model()

    def reload_model(self):
        """Step 7 — (re)load the trained model. Also called after retraining."""
        path = find_model_path(self.config)
        (self.model, self.user_to_index,
         self.movie_to_index, checkpoint) = load_trained_model(path, self.device)
        print(f"Model loaded from {path} | users: {checkpoint['num_users']:,} | "
              f"movies: {checkpoint['num_movies']:,} | "
              f"test RMSE: {checkpoint.get('test_rmse', float('nan')):.4f}")
        self.catalog.set_model_movies(self.movie_to_index)

        # App users already inside the model -> new accounts must get higher IDs
        largest_app_user = max(self.user_to_index) - self.max_csv_user_id
        if largest_app_user > 0:
            self.db.start_ids_after(largest_app_user)

        # Item vectors for cold-start similarity:
        # concatenated GMF + MLP movie embeddings, L2-normalised.
        with torch.no_grad():
            item_vectors = torch.cat(
                [self.model.movie_embedding_gmf.weight, self.model.movie_embedding_mlp.weight],
                dim=1,
            ).float()
            item_vectors = nn.functional.normalize(item_vectors, dim=1)
        self.item_vectors = item_vectors.cpu().numpy()

    def _check_weights(self):
        c = self.config
        if abs(c["w_similarity"] + c["w_genre"] + c["w_popularity"] - 1.0) > 1e-6:
            raise ValueError("Cold-start weights must sum to 1.0")
        if abs(c["w_new_genre"] + c["w_new_popularity"] - 1.0) > 1e-6:
            raise ValueError("New-movie fallback weights must sum to 1.0")

    # ---------------------------------------------------------
    # STEP 3A — REGISTER (new user)
    # ---------------------------------------------------------

    @classmethod
    def validate_username(cls, username):
        if not re.fullmatch(r"[A-Za-z0-9_]{3,30}", username or ""):
            return "Username must be 3–30 characters: letters, digits or underscore."
        if username.isdigit():
            return "Username must contain at least one letter (numbers are User IDs)."
        if username.lower().startswith(cls.CSV_ACCOUNT_PREFIX):
            return f"Usernames starting with '{cls.CSV_ACCOUNT_PREFIX}' are reserved."
        return None

    @staticmethod
    def validate_password(password):
        if len(password or "") < 6:
            return "Password must be at least 6 characters."
        return None

    def register(self, username, password):
        error = self.validate_username(username) or self.validate_password(password)
        if error:
            return None, error
        user_id = self.db.create_user(username, password)
        if user_id is None:
            return None, "Username already exists."
        return user_id, None

    # ---------------------------------------------------------
    # STEP 2 — NEW USER?  (automatic detection)
    # ---------------------------------------------------------

    def display_user_id(self, user):
        """The User ID shown to the person AND used inside the NCF model.
        MovieLens users keep their ratings.csv ID; app users get max ID + db id."""
        if user["movielens_user_id"] is not None:
            return int(user["movielens_user_id"])
        return self.max_csv_user_id + int(user["id"])

    def identify(self, text):
        """
        Decide who is opening the app from what they typed.

        Returns one of:
          ("csv",  movielens_user_id)  existing user found in ratings.csv
          ("app",  user_row)           existing user who registered in this app
          ("new",  username)           nobody found -> new user
          ("invalid", message)
        """
        text = (text or "").strip()
        if not text:
            return "invalid", "Please enter a User ID or a username."

        if text.isdigit():
            n = int(text)
            if n in self.csv_user_ids:
                return "csv", n
            if n > self.max_csv_user_id:
                user = self.db.get_user(n - self.max_csv_user_id)
                if user is not None and user["movielens_user_id"] is None:
                    return "app", user
            return "invalid", (f"User ID {n} was not found. "
                               "New here? Enter a username instead to sign up.")

        user = self.db.get_user_by_username(text)
        if user is not None:
            if user["movielens_user_id"] is not None:
                return "csv", int(user["movielens_user_id"])
            return "app", user
        return "new", text

    # ---------------------------------------------------------
    # STEP 3B — LOGIN (existing user)
    # ---------------------------------------------------------

    def get_or_create_csv_account(self, movielens_user_id):
        """
        Existing users from ratings.csv have no password in the dataset, so they
        log in with their User ID. The first time, a profile row is created in
        the database so their new feedback can be saved.
        """
        movielens_user_id = int(movielens_user_id)
        if movielens_user_id not in self.csv_user_ids:
            raise ValueError(f"User ID {movielens_user_id} is not in ratings.csv")
        user = self.db.get_user_by_movielens_id(movielens_user_id)
        if user is None:
            self.db.create_user(
                f"{self.CSV_ACCOUNT_PREFIX}{movielens_user_id}",
                secrets.token_hex(16),          # unused: dataset users log in by ID
                movielens_user_id=movielens_user_id,
                onboarded=True,
            )
            user = self.db.get_user_by_movielens_id(movielens_user_id)
        return user

    def login_app_user(self, user, password):
        verified = self.db.verify_login(user["username"], password)
        if verified is None:
            return None, "Wrong password."
        return verified, None

    # ---------------------------------------------------------
    # STEP 4A — CHOOSE 2–3 GENRES
    # ---------------------------------------------------------

    def validate_genres(self, genres):
        cleaned = []
        for g in genres:
            ng = self.catalog.normalise_genre(g)
            if ng is None:
                return None, f"Unknown genre: '{g}'"
            if ng not in cleaned:
                cleaned.append(ng)
        if not 2 <= len(cleaned) <= 3:
            return None, "Please choose 2 or 3 different genres."
        return cleaned, None

    # ---------------------------------------------------------
    # STEP 5A — POPULAR MOVIES FOR INITIAL RATING
    # ---------------------------------------------------------

    def onboarding_movies(self, genres):
        m = self.catalog.movies
        mask = (m["model_idx"].to_numpy() >= 0)
        genre_any = np.zeros(len(m), dtype=bool)
        for g in genres:
            genre_any |= self.catalog.genre_mask(g)
        pool = m[mask & genre_any].sort_values(
            ["vote_count", "weighted_rating"], ascending=False
        )
        return pool.head(self.config["onboarding_pool"])[["movieId", "title", "genres"]]

    @staticmethod
    def parse_rating(value):
        try:
            r = float(value)
        except (TypeError, ValueError):
            return None
        return r if r in VALID_RATINGS else None

    # ---------------------------------------------------------
    # STEP 6A — CREATE PROFILE
    # ---------------------------------------------------------

    def complete_onboarding(self, user_id, genres, initial_ratings):
        genres, error = self.validate_genres(genres)
        if error:
            return False, error
        if not 5 <= len(initial_ratings) <= 10:
            return False, "Please rate between 5 and 10 movies."
        for mid, r in initial_ratings.items():
            if not self.catalog.exists(mid):
                return False, f"Unknown movie ID {mid}."
            if float(r) not in VALID_RATINGS:
                return False, f"Invalid rating {r} (use 0.5 to 5.0 in steps of 0.5)."

        self.db.set_genres(user_id, genres)
        self.db.save_ratings(user_id, initial_ratings, source="onboarding")
        self.db.mark_onboarded(user_id)
        return True, None

    # ---------------------------------------------------------
    # STEP 4B / 6B — LOAD PROFILE + HISTORY
    # ---------------------------------------------------------

    def has_ncf_embedding(self, user):
        """True for MovieLens users and for app users added by retraining."""
        return self.display_user_id(user) in self.user_to_index

    def user_history(self, user):
        """All ratings: MovieLens history (if any) overridden by newer app ratings."""
        history = {}
        if user.get("movielens_user_id") is not None:
            history.update(self.catalog.movielens_history(user["movielens_user_id"]))
        history.update(self.db.get_ratings(user["id"]))
        return history

    def preferred_genres(self, user, history):
        chosen = self.db.get_genres(user["id"])
        if chosen:
            return chosen
        # Existing MovieLens users: derive from movies they rated 4.0 or higher
        liked = [mid for mid, r in history.items() if r >= 4.0]
        counts = {}
        for mid in liked:
            row = self.catalog.movie_id_to_row.get(mid)
            if row is None:
                continue
            for g in self.catalog.movies.at[row, "genres"].split("|"):
                if g in self.catalog.genre_to_col:
                    counts[g] = counts.get(g, 0) + 1
        return [g for g, _ in sorted(counts.items(), key=lambda x: -x[1])[:3]]

    def load_profile(self, user):
        history = self.user_history(user)
        return {
            "user": user,
            "history": history,
            "preferred_genres": self.preferred_genres(user, history),
            "has_ncf_embedding": self.has_ncf_embedding(user),
        }

    # ---------------------------------------------------------
    # STEP 8 — PREDICT (known movies)
    # ---------------------------------------------------------

    def _candidate_mask(self, rated_ids, genre_filter, min_votes, known):
        m = self.catalog.movies
        mask = (m["model_idx"].to_numpy() >= 0) if known else (m["model_idx"].to_numpy() < 0)
        if min_votes:
            mask &= m["vote_count"].to_numpy() >= min_votes
        mask &= self.catalog.genre_mask(genre_filter)
        if rated_ids:
            mask &= ~m["movieId"].isin(list(rated_ids)).to_numpy()
        return mask

    def _ncf_scores(self, user, rated_ids, genre_filter):
        """True NCF prediction for a user who has an embedding.
        Raw predictions are used for ranking: many movies can be predicted above 5.0,
        and clamping them first would make them all tie at 5.0 (random order).
        They are clamped to 0.5–5.0 only when shown."""
        mask = self._candidate_mask(rated_ids, genre_filter, self.config["min_votes_ncf"], True)
        rows = np.flatnonzero(mask)
        if len(rows) == 0:
            return pd.DataFrame(columns=["row", "score"])

        movie_idx = self.catalog.movies["model_idx"].to_numpy()[rows]
        user_idx = self.user_to_index[self.display_user_id(user)]

        preds = []
        with torch.no_grad():
            for start in range(0, len(movie_idx), 65536):
                chunk = torch.as_tensor(movie_idx[start:start + 65536], dtype=torch.long,
                                        device=self.device)
                users = torch.full_like(chunk, user_idx)
                out = self.model(users, chunk).float()
                preds.append(out.cpu().numpy())
        scores = np.concatenate(preds)
        return pd.DataFrame({"row": rows, "score": scores})

    def _cold_start_scores(self, history, preferred_genres, rated_ids, genre_filter):
        """
        Cold-start scoring for users WITHOUT an NCF embedding.
          score = w_sim * similarity to liked movies (NCF item embeddings)
                + w_genre * preferred-genre overlap
                + w_pop * popularity
        """
        c = self.config
        mask = self._candidate_mask(rated_ids, genre_filter, c["min_votes_cold_start"], True)
        rows = np.flatnonzero(mask)
        if len(rows) == 0:
            return pd.DataFrame(columns=["row", "score"])

        movies = self.catalog.movies
        model_idx = movies["model_idx"].to_numpy()

        # Taste vector: ratings centred on 3.0 (likes pull towards, dislikes push away)
        taste = np.zeros(self.item_vectors.shape[1], dtype=np.float64)
        for mid, r in history.items():
            row = self.catalog.movie_id_to_row.get(mid)
            if row is None or model_idx[row] < 0:
                continue
            taste += (r - 3.0) * self.item_vectors[model_idx[row]]

        norm = np.linalg.norm(taste)
        if norm > 1e-8:
            sim = self.item_vectors[model_idx[rows]] @ (taste / norm)   # [-1, 1]
            sim = (sim + 1.0) / 2.0                                     # [0, 1]
        else:
            sim = np.full(len(rows), 0.5)

        genre = self.catalog.genre_match_score(preferred_genres)[rows]
        pop = movies["popularity_score"].to_numpy()[rows]

        score = c["w_similarity"] * sim + c["w_genre"] * genre + c["w_popularity"] * pop
        return pd.DataFrame({"row": rows, "score": score})

    # ---------------------------------------------------------
    # STEP 9A — NEW MOVIE FALLBACK (movies unseen by NCF)
    # ---------------------------------------------------------

    def _new_movie_scores(self, preferred_genres, rated_ids, genre_filter):
        c = self.config
        mask = self._candidate_mask(rated_ids, genre_filter, 0, known=False)
        rows = np.flatnonzero(mask)
        if len(rows) == 0:
            return pd.DataFrame(columns=["row", "score"])
        genre = self.catalog.genre_match_score(preferred_genres)[rows]
        pop = self.catalog.movies["popularity_score"].to_numpy()[rows]
        score = c["w_new_genre"] * genre + c["w_new_popularity"] * pop
        return pd.DataFrame({"row": rows, "score": score})

    # ---------------------------------------------------------
    # STEP 10 — GENERATE TOP-K RECOMMENDATIONS
    # ---------------------------------------------------------

    def recommend(self, user, genre_filter=None, k=None):
        k = k or self.config["top_k"]
        if genre_filter is not None:
            normalised = self.catalog.normalise_genre(genre_filter)
            if normalised is None:
                raise ValueError(f"Unknown genre: '{genre_filter}'")
            genre_filter = normalised

        profile = self.load_profile(user)
        history = profile["history"]
        rated_ids = set(history.keys())
        prefs = profile["preferred_genres"]
        if genre_filter and genre_filter not in prefs:
            prefs = prefs + [genre_filter]

        # 9B / cold-start for movies NCF knows
        if profile["has_ncf_embedding"]:
            known = self._ncf_scores(user, rated_ids, genre_filter)
            method = "NCF"
        else:
            known = self._cold_start_scores(history, prefs, rated_ids, genre_filter)
            method = "Cold-start"

        # 9A — movies NCF has never seen
        new = self._new_movie_scores(prefs, rated_ids, genre_filter)

        known = known.sort_values("score", ascending=False, kind="stable")
        new = new.sort_values("score", ascending=False, kind="stable")

        n_new = min(self.config["new_movie_slots"], len(new), k)
        n_known = min(k - n_new, len(known))
        n_new = min(len(new), k - n_known)   # fill remaining slots if few known movies

        picks = []
        for _, r in known.head(n_known).iterrows():
            picks.append((int(r["row"]), float(r["score"]), method))
        for _, r in new.head(n_new).iterrows():
            picks.append((int(r["row"]), float(r["score"]), "New movie"))

        movies = self.catalog.movies
        results = []
        for rank, (row, score, source) in enumerate(picks, start=1):
            if source == "NCF":
                display = f"Predicted {min(max(score, 0.5), 5.0):.2f}/5"
            elif source == "New movie":
                # Separate reserved slots, scored by genre + popularity only
                display = f"Genre fit {score * 100:.0f}%"
            else:
                display = f"Match {score * 100:.0f}%"
            results.append({
                "rank": rank,
                "movieId": int(movies.at[row, "movieId"]),
                "title": movies.at[row, "title"],
                "genres": movies.at[row, "genres"],
                "score": round(score, 4),
                "display": display,
                "source": source,
            })
        return pd.DataFrame(results)

    # ---------------------------------------------------------
    # STEP 11 + 12 — FEEDBACK -> SAVE RATINGS DATABASE
    # ---------------------------------------------------------

    def submit_feedback(self, user, ratings):
        clean = {}
        for mid, r in ratings.items():
            if not self.catalog.exists(mid):
                return False, f"Unknown movie ID {mid}."
            parsed = self.parse_rating(r)
            if parsed is None:
                return False, f"Invalid rating {r} (use 0.5 to 5.0 in steps of 0.5)."
            clean[int(mid)] = parsed
        if not clean:
            return False, "No ratings given."
        self.db.save_ratings(user["id"], clean, source="feedback")
        return True, None

    # ---------------------------------------------------------
    # STEP 13 (part 1) — EXPORT NEW RATINGS FOR RETRAINING
    # ---------------------------------------------------------

    def export_feedback_for_retraining(self, out_path):
        """
        Writes app ratings in MovieLens format (userId,movieId,rating,timestamp).
        App-only users get new IDs above the largest MovieLens userId so they
        never collide with existing users when added to the training data.
        """
        rows = []
        for r in self.db.all_ratings_with_users():
            uid = r["movielens_user_id"] if r["movielens_user_id"] is not None \
                else self.max_csv_user_id + r["user_id"]       # same rule as display_user_id()
            ts = int(datetime.fromisoformat(r["rated_at"]).timestamp())
            rows.append((int(uid), int(r["movie_id"]), float(r["rating"]), ts))
        df = pd.DataFrame(rows, columns=["userId", "movieId", "rating", "timestamp"])
        df.to_csv(out_path, index=False)
        return df


