def on_retrain():
    """STEP 13 — retrain with the app ratings; the printed log is shown in the UI."""
    if state["retraining"]:
        return BUSY, gr.update()
    state["retraining"] = True
    log = io.StringIO()
    try:
        with contextlib.redirect_stdout(log):
            retrain_model(engine)
    except Exception as error:                     # show the problem instead of a silent failure
        log.write(f"\n Retraining failed: {error}")
    finally:
        state["retraining"] = False
    return log.getvalue(), model_info_text()


