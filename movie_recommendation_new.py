class MovieCatalog:
    """Movie metadata + popularity statistics computed from ratings.csv."""

    def __init__(self, movies_path, ratings_path, prior_votes):
        movies = pd.read_csv(movies_path)
        movies = movies.drop_duplicates(subset=["movieId"]).copy()
        movies["genres"] = movies["genres"].fillna(NO_GENRE).str.strip()
        movies["movieId"] = movies["movieId"].astype(np.int64)
        movies = movies.reset_index(drop=True)

        print("Loading ratings (history + popularity statistics)...")
        # float32 = 4 bytes per value (pandas default is 8) and it can hold missing values;
        # IDs in MovieLens are far below 16 million, so float32 stores them exactly
        ratings = pd.read_csv(ratings_path, usecols=["userId", "movieId", "rating"],
                              dtype="float32")
        # same cleaning as the offline phase: one rating per user-movie pair, no missing values
        ratings = ratings.drop_duplicates(subset=["userId", "movieId"])
        ratings = ratings.dropna(subset=["userId", "movieId", "rating"])
        ratings = ratings.astype({"userId": np.int32, "movieId": np.int32})
        # Sorted by user, so one user's history is found instantly with searchsorted
        # (instead of scanning all 32 million rows every time)
        ratings = ratings.sort_values("userId", kind="stable").reset_index(drop=True)
        self.ratings = ratings
        self.rating_user_ids = ratings["userId"].to_numpy()

        # ---- Popularity (Bayesian weighted rating) ----
        stats = ratings.groupby("movieId")["rating"].agg(["count", "mean"])
        global_mean = float(ratings["rating"].mean())

        movies["vote_count"] = (
            movies["movieId"].map(stats["count"]).fillna(0).astype(np.int64)
        )
        movies["avg_rating"] = (
            movies["movieId"].map(stats["mean"]).fillna(global_mean).astype(np.float64)
        )
        v = movies["vote_count"].to_numpy(dtype=np.float64)
        r = movies["avg_rating"].to_numpy(dtype=np.float64)
        m = float(prior_votes)
        movies["weighted_rating"] = (v * r + m * global_mean) / (v + m)

        # Popularity normalised to [0, 1] on the 0.5–5.0 scale
        movies["popularity_score"] = ((movies["weighted_rating"] - 0.5) / 4.5).clip(0.0, 1.0)
        movies["model_idx"] = -1     # filled by set_model_movies()

        # ---- Genre multi-hot matrix ----
        genre_lists = movies["genres"].str.split("|")
        all_genres = sorted(
            {g for gl in genre_lists for g in gl if g and g != NO_GENRE}
        )
        self.genres = all_genres
        self.genre_to_col = {g: i for i, g in enumerate(all_genres)}

        multi_hot = np.zeros((len(movies), len(all_genres)), dtype=np.float32)
        for row, gl in enumerate(genre_lists):
            for g in gl:
                col = self.genre_to_col.get(g)
                if col is not None:
                    multi_hot[row, col] = 1.0
        self.multi_hot = multi_hot

        self.movies = movies
        self.movie_id_to_row = {int(mid): i for i, mid in enumerate(movies["movieId"])}
        self.global_mean = global_mean

    def set_model_movies(self, movie_to_index):
        """model_idx = position of the movie inside NCF, -1 = NCF has never seen it.
        Called again after retraining because the mapping changes."""
        self.movies["model_idx"] = (
            self.movies["movieId"].map(movie_to_index).fillna(-1).astype(np.int64)
        )
        print(f"Catalog: {len(self.movies):,} movies | "
              f"{int((self.movies['model_idx'] >= 0).sum()):,} known to NCF | "
              f"{len(self.genres)} genres")

    # ---------- helpers ----------

    def exists(self, movie_id):
        return int(movie_id) in self.movie_id_to_row

    def title(self, movie_id):
        row = self.movie_id_to_row.get(int(movie_id))
        return None if row is None else self.movies.at[row, "title"]

    def normalise_genre(self, genre):
        """Case-insensitive match against the dataset's genre names."""
        if genre is None:
            return None
        lookup = {g.lower(): g for g in self.genres}
        return lookup.get(str(genre).strip().lower())

    def genre_mask(self, genre):
        """Boolean mask of catalog rows containing `genre` (None -> all rows)."""
        if genre is None:
            return np.ones(len(self.movies), dtype=bool)
        return self.multi_hot[:, self.genre_to_col[genre]] > 0

    def genre_match_score(self, preferred_genres):
        """Fraction of the user's preferred genres each movie contains -> [0, 1]."""
        cols = [self.genre_to_col[g] for g in preferred_genres if g in self.genre_to_col]
        if not cols:
            return np.zeros(len(self.movies), dtype=np.float64)
        return self.multi_hot[:, cols].sum(axis=1).astype(np.float64) / len(cols)

    def movielens_history(self, movielens_user_id):
        start = np.searchsorted(self.rating_user_ids, int(movielens_user_id), side="left")
        end = np.searchsorted(self.rating_user_ids, int(movielens_user_id), side="right")
        hist = self.ratings.iloc[start:end]
        return dict(zip(hist["movieId"].tolist(), hist["rating"].tolist()))


