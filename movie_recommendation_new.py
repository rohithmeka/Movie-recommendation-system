def evaluate_model(
    model,
    loader
):

    model.eval()

    squared_error = 0.0
    absolute_error = 0.0
    total_samples = 0


    with torch.no_grad():

        for users, movies, ratings in loader:

            users = users.to(
                device,
                non_blocking=True
            )

            movies = movies.to(
                device,
                non_blocking=True
            )

            ratings = ratings.to(
                device,
                non_blocking=True
            )


            if use_amp:

                with torch.autocast(
                    device_type="cuda",
                    dtype=torch.float16
                ):

                    predictions = model(
                        users,
                        movies
                    )

            else:

                predictions = model(
                    users,
                    movies
                )


            # Keep predictions inside the actual rating range
            predictions = torch.clamp(
                predictions,
                min=0.5,
                max=5.0
            )


            squared_error += torch.sum(
                (predictions - ratings) ** 2
            ).item()


            absolute_error += torch.sum(
                torch.abs(
                    predictions - ratings
                )
            ).item()


            total_samples += ratings.size(0)


    mse = (
        squared_error /
        total_samples
    )


    rmse = np.sqrt(mse)


    mae = (
        absolute_error /
        total_samples
    )


    return rmse, mae


