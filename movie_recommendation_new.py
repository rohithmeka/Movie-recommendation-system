# NCF MODEL — must be IDENTICAL to the offline training class
# ============================================================

class NCF(nn.Module):

    def __init__(self, num_users, num_movies, embedding_dim=32):
        super().__init__()

        # GMF component
        self.user_embedding_gmf = nn.Embedding(num_users, embedding_dim)
        self.movie_embedding_gmf = nn.Embedding(num_movies, embedding_dim)

        # MLP component
        self.user_embedding_mlp = nn.Embedding(num_users, embedding_dim)
        self.movie_embedding_mlp = nn.Embedding(num_movies, embedding_dim)

        self.mlp = nn.Sequential(
            nn.Linear(embedding_dim * 2, 128),
            nn.ReLU(),
            nn.Dropout(0.20),
            nn.Linear(128, 64),
            nn.ReLU(),
            nn.Dropout(0.20),
            nn.Linear(64, 32),
            nn.ReLU(),
        )

        self.output_layer = nn.Linear(embedding_dim + 32, 1)

        for embedding in [self.user_embedding_gmf, self.movie_embedding_gmf,
                          self.user_embedding_mlp, self.movie_embedding_mlp]:
            nn.init.normal_(embedding.weight, mean=0.0, std=0.01)

    def forward(self, user_ids, movie_ids):
        gmf_vector = self.user_embedding_gmf(user_ids) * self.movie_embedding_gmf(movie_ids)

        mlp_input = torch.cat(
            [self.user_embedding_mlp(user_ids), self.movie_embedding_mlp(movie_ids)],
            dim=1,
        )
        mlp_vector = self.mlp(mlp_input)

        combined = torch.cat([gmf_vector, mlp_vector], dim=1)
        return self.output_layer(combined).squeeze(1)


