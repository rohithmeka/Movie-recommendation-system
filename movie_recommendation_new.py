class NCF(nn.Module):

    def __init__(
        self,
        num_users,
        num_movies,
        embedding_dim=32
    ):

        super().__init__()


        # ====================================================
        # GMF COMPONENT
        # ====================================================
        #
        # Generalized Matrix Factorization learns a
        # multiplicative interaction between user and movie
        # embeddings.
        # ====================================================

        self.user_embedding_gmf = nn.Embedding(
            num_users,
            embedding_dim
        )

        self.movie_embedding_gmf = nn.Embedding(
            num_movies,
            embedding_dim
        )


        # ====================================================
        # MLP COMPONENT
        # ====================================================
        #
        # A separate embedding space is used for the
        # neural network component.
        # ====================================================

        self.user_embedding_mlp = nn.Embedding(
            num_users,
            embedding_dim
        )

        self.movie_embedding_mlp = nn.Embedding(
            num_movies,
            embedding_dim
        )


        # ====================================================
        # MLP NETWORK
        # ====================================================

        self.mlp = nn.Sequential(

            nn.Linear(
                embedding_dim * 2,
                128
            ),

            nn.ReLU(),

            nn.Dropout(0.20),


            nn.Linear(
                128,
                64
            ),

            nn.ReLU(),

            nn.Dropout(0.20),


            nn.Linear(
                64,
                32
            ),

            nn.ReLU()

        )


        # ====================================================
        # FINAL NCF OUTPUT
        # ====================================================
        #
        # GMF output = embedding_dim
        # MLP output = 32
        #
        # Combined = embedding_dim + 32
        # ====================================================

        self.output_layer = nn.Linear(
            embedding_dim + 32,
            1
        )


        # ====================================================
        # WEIGHT INITIALIZATION
        # ====================================================

        nn.init.normal_(
            self.user_embedding_gmf.weight,
            mean=0.0,
            std=0.01
        )

        nn.init.normal_(
            self.movie_embedding_gmf.weight,
            mean=0.0,
            std=0.01
        )

        nn.init.normal_(
            self.user_embedding_mlp.weight,
            mean=0.0,
            std=0.01
        )

        nn.init.normal_(
            self.movie_embedding_mlp.weight,
            mean=0.0,
            std=0.01
        )


    def forward(
        self,
        user_ids,
        movie_ids
    ):

        # ====================================================
        # GMF PATH
        # ====================================================

        user_gmf = self.user_embedding_gmf(
            user_ids
        )

        movie_gmf = self.movie_embedding_gmf(
            movie_ids
        )

        gmf_vector = (
            user_gmf * movie_gmf
        )


        # ====================================================
        # MLP PATH
        # ====================================================

        user_mlp = self.user_embedding_mlp(
            user_ids
        )

        movie_mlp = self.movie_embedding_mlp(
            movie_ids
        )


        mlp_input = torch.cat(
            [
                user_mlp,
                movie_mlp
            ],
            dim=1
        )


        mlp_vector = self.mlp(
            mlp_input
        )


        # ====================================================
        # COMBINE GMF + MLP
        # ====================================================

        combined = torch.cat(
            [
                gmf_vector,
                mlp_vector
            ],
            dim=1
        )


        # ====================================================
        # PREDICT RATING
        # ====================================================

        prediction = self.output_layer(
            combined
        )


        return prediction.squeeze(1)


