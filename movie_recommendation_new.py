def load_trained_model(model_path, device):
    # weights_only=False: the checkpoint also stores Python dicts (ID mappings).
    # This is our own trusted file produced by the offline phase.
    checkpoint = torch.load(model_path, map_location=device, weights_only=False)

    model = NCF(
        num_users=checkpoint["num_users"],
        num_movies=checkpoint["num_movies"],
        embedding_dim=checkpoint["embedding_dim"],
    ).to(device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()

    # Normalise mapping key/value types to plain Python ints
    user_to_index = {int(k): int(v) for k, v in checkpoint["user_to_index"].items()}
    movie_to_index = {int(k): int(v) for k, v in checkpoint["movie_to_index"].items()}

    return model, user_to_index, movie_to_index, checkpoint


