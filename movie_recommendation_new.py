def train_one_epoch(
    model,
    loader,
    optimizer,
    criterion,
    scaler
):

    model.train()

    total_loss = 0.0
    total_samples = 0


    for users, movies, ratings in loader:

        users = users.to(
            device,
            non_blocking=True
        )

        movies = movies.to(
            device,
            non_blocking=True
        )

        ratings = ratings.to(
            device,
            non_blocking=True
        )


        optimizer.zero_grad(
            set_to_none=True
        )


        # ----------------------------------------------------
        # GPU mixed precision
        # ----------------------------------------------------

        if use_amp:

            with torch.autocast(
                device_type="cuda",
                dtype=torch.float16
            ):

                predictions = model(
                    users,
                    movies
                )

                loss = criterion(
                    predictions,
                    ratings
                )


            scaler.scale(
                loss
            ).backward()


            scaler.step(
                optimizer
            )


            scaler.update()


        else:

            predictions = model(
                users,
                movies
            )

            loss = criterion(
                predictions,
                ratings
            )

            loss.backward()

            optimizer.step()


        batch_size = ratings.size(0)

        total_loss += (
            loss.detach().item()
            * batch_size
        )

        total_samples += batch_size


    return (
        total_loss /
        total_samples
    )


