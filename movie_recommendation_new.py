def on_continue(text, password):
    if state["retraining"]:
        return {login_msg: BUSY}
    kind, value = engine.identify(text)

    if kind == "invalid":
        return {login_msg: f"{value}"}

    if kind == "csv":                                    # existing MovieLens user
        user = engine.get_or_create_csv_account(value)
        return open_main(user, f"User ID {value} found in ratings.csv → **existing user**")

    if kind == "app":                                    # existing app user
        if not password:
            return {login_msg: " Account found → **existing user**. Enter your password "
                               "and press Continue."}
        user, error = engine.login_app_user(value, password)
        if error:
            return {login_msg: f" {error}"}
        if not user["onboarded"]:                        # sign-up was not finished earlier
            return open_signup(user["username"], user,
                               "Your profile is incomplete — choose genres and rate movies.")
        return open_main(user, " Logged in → **existing user**")

    error = engine.validate_username(value)              # new user
    if error:
        return {login_msg: f" {error}"}
    return open_signup(value, None, "No account with this name was found, "
                                    "so let's create your profile.")


