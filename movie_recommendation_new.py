class UserDatabase:

    def __init__(self, db_path):
        self.conn = sqlite3.connect(db_path, check_same_thread=False)
        self.conn.row_factory = sqlite3.Row
        self.conn.execute("PRAGMA foreign_keys = ON")
        self._create_tables()

    def _create_tables(self):
        self.conn.executescript(
            """
            CREATE TABLE IF NOT EXISTS users (
                id                 INTEGER PRIMARY KEY AUTOINCREMENT,
                username           TEXT UNIQUE NOT NULL,
                password_hash      TEXT NOT NULL,
                salt               TEXT NOT NULL,
                movielens_user_id  INTEGER UNIQUE,
                onboarded          INTEGER NOT NULL DEFAULT 0,
                created_at         TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS user_genres (
                user_id  INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                genre    TEXT NOT NULL,
                PRIMARY KEY (user_id, genre)
            );

            CREATE TABLE IF NOT EXISTS ratings (
                user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                movie_id  INTEGER NOT NULL,
                rating    REAL NOT NULL,
                rated_at  TEXT NOT NULL,
                source    TEXT NOT NULL,
                PRIMARY KEY (user_id, movie_id)
            );
            """
        )
        self.conn.commit()

    # ---------- password hashing ----------

    @staticmethod
    def _hash_password(password, salt):
        digest = hashlib.pbkdf2_hmac(
            "sha256", password.encode("utf-8"), bytes.fromhex(salt), 100_000
        )
        return digest.hex()

    # ---------- accounts ----------

    def create_user(self, username, password, movielens_user_id=None, onboarded=False):
        salt = secrets.token_hex(16)
        try:
            cur = self.conn.execute(
                "INSERT INTO users (username, password_hash, salt, movielens_user_id, "
                "onboarded, created_at) VALUES (?, ?, ?, ?, ?, ?)",
                (
                    username,
                    self._hash_password(password, salt),
                    salt,
                    movielens_user_id,
                    1 if onboarded else 0,
                    datetime.now(timezone.utc).isoformat(),
                ),
            )
            self.conn.commit()
            return cur.lastrowid
        except sqlite3.IntegrityError:
            return None

    def start_ids_after(self, last_id):
        """New users must get an ID the trained model has never seen.
        (Matters if movie_app.db is deleted but a retrained model is kept.)"""
        row = self.conn.execute(
            "SELECT seq FROM sqlite_sequence WHERE name = 'users'"
        ).fetchone()
        if row is None:
            self.conn.execute(
                "INSERT INTO sqlite_sequence (name, seq) VALUES ('users', ?)", (last_id,)
            )
        elif row["seq"] < last_id:
            self.conn.execute(
                "UPDATE sqlite_sequence SET seq = ? WHERE name = 'users'", (last_id,)
            )
        self.conn.commit()

    def verify_login(self, username, password):
        row = self.conn.execute(
            "SELECT * FROM users WHERE username = ?", (username,)
        ).fetchone()
        if row is None:
            return None
        attempt = self._hash_password(password, row["salt"])
        if hmac.compare_digest(attempt, row["password_hash"]):
            return dict(row)
        return None

    def get_user(self, user_id):
        row = self.conn.execute("SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
        return None if row is None else dict(row)

    def get_user_by_username(self, username):
        row = self.conn.execute(
            "SELECT * FROM users WHERE username = ?", (username,)
        ).fetchone()
        return None if row is None else dict(row)

    def get_user_by_movielens_id(self, movielens_user_id):
        row = self.conn.execute(
            "SELECT * FROM users WHERE movielens_user_id = ?", (int(movielens_user_id),)
        ).fetchone()
        return None if row is None else dict(row)

    def mark_onboarded(self, user_id):
        self.conn.execute("UPDATE users SET onboarded = 1 WHERE id = ?", (user_id,))
        self.conn.commit()

    # ---------- genres ----------

    def set_genres(self, user_id, genres):
        self.conn.execute("DELETE FROM user_genres WHERE user_id = ?", (user_id,))
        self.conn.executemany(
            "INSERT INTO user_genres (user_id, genre) VALUES (?, ?)",
            [(user_id, g) for g in genres],
        )
        self.conn.commit()

    def get_genres(self, user_id):
        rows = self.conn.execute(
            "SELECT genre FROM user_genres WHERE user_id = ? ORDER BY genre", (user_id,)
        ).fetchall()
        return [r["genre"] for r in rows]

    # ---------- ratings ----------

    def save_ratings(self, user_id, ratings, source):
        now = datetime.now(timezone.utc).isoformat()
        self.conn.executemany(
            "INSERT INTO ratings (user_id, movie_id, rating, rated_at, source) "
            "VALUES (?, ?, ?, ?, ?) "
            "ON CONFLICT(user_id, movie_id) DO UPDATE SET "
            "rating = excluded.rating, rated_at = excluded.rated_at, source = excluded.source",
            [(user_id, int(mid), float(r), now, source) for mid, r in ratings.items()],
        )
        self.conn.commit()

    def get_ratings(self, user_id):
        rows = self.conn.execute(
            "SELECT movie_id, rating FROM ratings WHERE user_id = ? ORDER BY rated_at",
            (user_id,),
        ).fetchall()
        return {int(r["movie_id"]): float(r["rating"]) for r in rows}

    def all_ratings_with_users(self):
        return self.conn.execute(
            "SELECT r.user_id, u.movielens_user_id, r.movie_id, r.rating, r.rated_at "
            "FROM ratings r JOIN users u ON u.id = r.user_id"
        ).fetchall()

    def close(self):
        self.conn.close()


