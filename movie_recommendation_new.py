def on_create(pending_user, password, genres, movie_ids, *ratings):
    if state["retraining"]:
        return {signup_msg: BUSY}
    if not movie_ids:
        return {signup_msg: " Choose your genres and click 'Show movies to rate' first."}

    first_ratings = {}
    for movie_id, rating in zip(movie_ids, ratings):
        if rating and rating != NOT_SEEN:
            first_ratings[int(movie_id)] = float(rating)

    # check everything BEFORE creating the account, so no half-made accounts are left
    genres, error = engine.validate_genres(genres or [])
    if not error and not 5 <= len(first_ratings) <= 10:
        error = f"Please rate between 5 and 10 movies (you rated {len(first_ratings)})."
    user = pending_user["user"]
    if not error and user is None:
        error = engine.validate_password(password)
    if error:
        return {signup_msg: f" {error}"}

    if user is None:                                     # 3A register
        user_id, error = engine.register(pending_user["name"], password)
        if error:
            return {signup_msg: f" {error}"}
        user = engine.db.get_user(user_id)

    ok, error = engine.complete_onboarding(user["id"], genres, first_ratings)   # 4A-6A
    if not ok:
        return {signup_msg: f" {error}"}
    user = engine.db.get_user(user["id"])
    return open_main(user, f"🎉 Profile created! Log in next time with **{user['username']}** "
                           f"or User ID **{engine.display_user_id(user)}**.")


